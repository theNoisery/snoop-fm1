"""SNOOP: the boot splash from The Noisery's logo (assets/noisery-logo-240x188.png), in the format of
tools/gen_logo.py (sloop_logo.h: SLOOP_SPLASH_W/H, a 16-colour palette, RLE runs of (run - 1) << 4 | colour).
The logo is grey on black: brightened to white, its 16 levels of grey kept (the anti-aliased edges).

  tools/gen_snoop_logo.py OUT.h
"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "noisery-logo-240x188.png"
W, H = 240, 188
WHITE = 236


def rgb565(v):
    return ((v >> 3) << 11) | ((v >> 2) << 5) | (v >> 3)


def main(out):
    im = Image.open(SRC).convert("L")
    if im.size != (W, H):
        im = im.resize((W, H), Image.LANCZOS)
    top = max(im.getextrema()[1], 1)
    px = [min(15, round(v * 15 / top)) for v in im.tobytes()]      # 16 levels, the brightest white
    pal = [round(WHITE * k / 15) for k in range(16)]
    rle = bytearray()
    i = 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == px[i] and j - i < 16:
            j += 1
        rle.append(((j - i - 1) << 4) | px[i])
        i = j
    L = ["/* generated by tools/gen_snoop_logo.py: the SNOOP boot splash (The Noisery) */", "#pragma once",
         "#include <stdint.h>", f"#define SLOOP_SPLASH_W {W}", f"#define SLOOP_SPLASH_H {H}",
         "static const uint16_t SLOOP_SPLASH_PAL[16] = {" + ", ".join(f"0x{rgb565(v):04X}" for v in pal) + "};",
         f"static const uint8_t SLOOP_SPLASH_RLE[{len(rle)}] = {{"]
    for k in range(0, len(rle), 24):
        L.append("    " + ", ".join(str(b) for b in rle[k:k + 24]) + ",")
    L.append("};")
    Path(out).write_text("\n".join(L) + "\n")
    print(f"logo: The Noisery, splash {W}x{H}, {len(rle)} B RLE -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
